/**
 * Retrieves a translated string for the given key and language.
 * Falls back to English if key is missing in the target language.
 */
export function t(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const dict = translations[lang] ?? translations['en'];
  let str = dict[key] ?? translations['en'][key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }
  return str;
}
